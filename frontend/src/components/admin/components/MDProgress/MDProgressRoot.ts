// @mui material components
import { styled } from "@mui/material/styles";
import LinearProgress from "@mui/material/LinearProgress";
import type { CSSObject } from "@mui/material/styles";

// Material Dashboard 2 React theme types
import type { MainColor } from "@/components/admin/assets/theme/types";

export type MDProgressColor = MainColor;
export type MDProgressVariant = "contained" | "gradient";

export interface MDProgressOwnerState {
  color: MDProgressColor;
  value: number;
  variant: MDProgressVariant;
}

export default styled(LinearProgress)<{ ownerState: MDProgressOwnerState }>(({
  theme,
  ownerState,
}): CSSObject => {
  const { palette, functions } = theme;
  const { color, value, variant } = ownerState;

  const { text, gradients } = palette;
  const { linearGradient } = functions;

  // background value
  let backgroundValue: string;

  if (variant === "gradient") {
    backgroundValue = gradients[color]
      ? linearGradient(gradients[color].main, gradients[color].state)
      : linearGradient(gradients.info.main, gradients.info.state);
  } else {
    backgroundValue = palette[color] ? palette[color].main : palette.info.main;
  }

  return {
    "& .MuiLinearProgress-bar": {
      background: backgroundValue,
      width: `${value}%`,
      color: text.main,
    },
  };
});
