// @mui material components
import Icon from "@/components/admin/ui/Icon";
import { styled } from "@mui/material/styles";
import type { CSSObject } from "@mui/material/styles";

// Material Dashboard 2 React theme types
import type { MainColor } from "@/components/admin/assets/theme/types";

export type MDSnackbarColor = MainColor;

export interface MDSnackbarIconOwnerState {
  color: MDSnackbarColor;
  bgWhite: boolean;
}

export default styled(Icon)<{ ownerState: MDSnackbarIconOwnerState }>(({
  theme,
  ownerState,
}): CSSObject => {
  const { palette, functions, typography } = theme;
  const { color, bgWhite } = ownerState;

  const { white, transparent, gradients } = palette;
  const { pxToRem, linearGradient } = functions;
  const { size } = typography;

  // backgroundImage value
  let backgroundImageValue: string | undefined;

  if (bgWhite) {
    backgroundImageValue = gradients[color]
      ? linearGradient(gradients[color].main, gradients[color].state)
      : linearGradient(gradients.info.main, gradients.info.state);
  } else if (color === "light") {
    backgroundImageValue = linearGradient(gradients.dark.main, gradients.dark.state);
  }

  return {
    backgroundImage: backgroundImageValue,
    WebkitTextFillColor: bgWhite || color === "light" ? transparent.main : white.main,
    WebkitBackgroundClip: "text",
    marginRight: pxToRem(8),
    fontSize: size.lg,
    transform: `translateY(${pxToRem(-2)})`,
  };
});
